-- LAMB Academic - V5: catalogos de tramite para los expedientes de Base Universal
-- Ejecutar como LAMB_APP despues de V4 y de un respaldo Data Pump.
--
-- Agrega:
--   * Catalogos: CATEGORIAS_TRAMITE, DESTINATARIOS, TIPOS_DOCUMENTO_INSTITUCIONAL y TIPOS_SOLICITUD
--     (cada tipo pertenece a una categoria y sugiere un destinatario).
--   * REQUISITOS_TIPO_SOLICITUD: documentos que pide cada tipo (OBLIGATORIO = 1) o que recomienda (0).
--   * EXPEDIENTES: categoria, tipo de solicitud y destinatario.
--   * DOCUMENTOS_ADJUNTOS: tipo de documento institucional, tamano del archivo cargado y enlace de
--     SharePoint. Un documento tiene archivo (o ruta declarada) O enlace, nunca los dos.
--   * SEQ_CODIGO_TRAMITE: el servidor genera el codigo TR-AAAA-NNNNN.
--   * Un titular no tiene dos expedientes del mismo tipo en REGISTRADO, EN_REVISION u OBSERVADO.
--   * Datos iniciales de los catalogos (necesarios para registrar expedientes; no son datos demo).
--
-- Script ADITIVO para los registros existentes: las columnas nuevas son NULL, y TIPO_DOCUMENTO y
-- RUTA_ARCHIVO pasan a admitir NULL solo para los documentos con enlace. Los expedientes y documentos
-- previos quedan "sin tipo de solicitud" y no se les exigen requisitos.
-- Los nombres con tildes usan UNISTR para no depender del juego de caracteres del cliente SQL*Plus.
-- Reversion: V5__rollback.sql (requiere autorizacion; borra los documentos con enlace).
-- =============================================================================

WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET ECHO ON

-- --------------------------------- Catalogos ---------------------------------

CREATE TABLE CATEGORIAS_TRAMITE (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO       VARCHAR2(30)  NOT NULL,
    NOMBRE       VARCHAR2(150) NOT NULL,
    DESCRIPCION  VARCHAR2(255),
    ACTIVO       NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_CATEGORIAS_TRAMITE PRIMARY KEY (ID),
    CONSTRAINT UK_CATEGORIAS_TRAMITE_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_CATEGORIAS_TRAMITE_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE DESTINATARIOS (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO       VARCHAR2(30)  NOT NULL,
    NOMBRE       VARCHAR2(150) NOT NULL,
    DESCRIPCION  VARCHAR2(255),
    ACTIVO       NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_DESTINATARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_DESTINATARIOS_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_DESTINATARIOS_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE TIPOS_DOCUMENTO_INSTITUCIONAL (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO       VARCHAR2(30)  NOT NULL,
    NOMBRE       VARCHAR2(150) NOT NULL,
    DESCRIPCION  VARCHAR2(255),
    ACTIVO       NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_TIPOS_DOCUMENTO_INST PRIMARY KEY (ID),
    CONSTRAINT UK_TIPOS_DOCUMENTO_INST_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_TIPOS_DOCUMENTO_INST_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE TABLE TIPOS_SOLICITUD (
    ID                        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CATEGORIA              NUMBER NOT NULL,
    CODIGO                    VARCHAR2(30)  NOT NULL,
    NOMBRE                    VARCHAR2(150) NOT NULL,
    DESCRIPCION               VARCHAR2(255),
    ID_DESTINATARIO_SUGERIDO  NUMBER NOT NULL,
    ACTIVO                    NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_TIPOS_SOLICITUD PRIMARY KEY (ID),
    CONSTRAINT UK_TIPOS_SOLICITUD_CODIGO UNIQUE (CODIGO),
    CONSTRAINT FK_TIPOS_SOLICITUD_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS_TRAMITE (ID),
    CONSTRAINT FK_TIPOS_SOLICITUD_DESTINATARIO FOREIGN KEY (ID_DESTINATARIO_SUGERIDO) REFERENCES DESTINATARIOS (ID),
    CONSTRAINT CK_TIPOS_SOLICITUD_ACTIVO CHECK (ACTIVO IN (0, 1))
);

CREATE INDEX IX_TIPOS_SOLICITUD_CATEGORIA ON TIPOS_SOLICITUD (ID_CATEGORIA);
CREATE INDEX IX_TIPOS_SOLICITUD_DESTINATARIO ON TIPOS_SOLICITUD (ID_DESTINATARIO_SUGERIDO);

CREATE TABLE REQUISITOS_TIPO_SOLICITUD (
    ID_TIPO_SOLICITUD  NUMBER NOT NULL,
    ID_TIPO_DOCUMENTO  NUMBER NOT NULL,
    OBLIGATORIO        NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_REQUISITOS_TIPO_SOLICITUD PRIMARY KEY (ID_TIPO_SOLICITUD, ID_TIPO_DOCUMENTO),
    CONSTRAINT FK_REQUISITOS_TIPO_SOLICITUD FOREIGN KEY (ID_TIPO_SOLICITUD) REFERENCES TIPOS_SOLICITUD (ID),
    CONSTRAINT FK_REQUISITOS_TIPO_DOCUMENTO FOREIGN KEY (ID_TIPO_DOCUMENTO) REFERENCES TIPOS_DOCUMENTO_INSTITUCIONAL (ID),
    CONSTRAINT CK_REQUISITOS_OBLIGATORIO CHECK (OBLIGATORIO IN (0, 1))
);

CREATE INDEX IX_REQUISITOS_TIPO_DOCUMENTO ON REQUISITOS_TIPO_SOLICITUD (ID_TIPO_DOCUMENTO);

-- -------------------------------- Expedientes --------------------------------

ALTER TABLE EXPEDIENTES ADD (
    ID_CATEGORIA       NUMBER,
    ID_TIPO_SOLICITUD  NUMBER,
    ID_DESTINATARIO    NUMBER
);

ALTER TABLE EXPEDIENTES ADD CONSTRAINT FK_EXPEDIENTES_CATEGORIA
    FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS_TRAMITE (ID);
ALTER TABLE EXPEDIENTES ADD CONSTRAINT FK_EXPEDIENTES_TIPO_SOLICITUD
    FOREIGN KEY (ID_TIPO_SOLICITUD) REFERENCES TIPOS_SOLICITUD (ID);
ALTER TABLE EXPEDIENTES ADD CONSTRAINT FK_EXPEDIENTES_DESTINATARIO
    FOREIGN KEY (ID_DESTINATARIO) REFERENCES DESTINATARIOS (ID);

CREATE INDEX IX_EXPEDIENTES_TIPO_SOLICITUD ON EXPEDIENTES (ID_TIPO_SOLICITUD);
CREATE INDEX IX_EXPEDIENTES_CATEGORIA ON EXPEDIENTES (ID_CATEGORIA);
CREATE INDEX IX_EXPEDIENTES_DESTINATARIO ON EXPEDIENTES (ID_DESTINATARIO);

-- Un solo expediente en tramite por titular y tipo. Las filas previas (sin tipo) y los expedientes
-- APROBADO o ARCHIVADO dan una clave totalmente NULL, que Oracle no indexa.
CREATE UNIQUE INDEX UX_EXPEDIENTES_TIPO_EN_CURSO ON EXPEDIENTES (
    CASE WHEN ID_TIPO_SOLICITUD IS NOT NULL AND ESTADO IN ('REGISTRADO', 'EN_REVISION', 'OBSERVADO')
         THEN ID_PERSONA END,
    CASE WHEN ID_TIPO_SOLICITUD IS NOT NULL AND ESTADO IN ('REGISTRADO', 'EN_REVISION', 'OBSERVADO')
         THEN ID_TIPO_SOLICITUD END
);

-- ---------------------------- Documentos adjuntos ----------------------------

ALTER TABLE DOCUMENTOS_ADJUNTOS ADD (
    ID_TIPO_DOCUMENTO_INST  NUMBER,
    TAMANO_BYTES            NUMBER(12),
    ENLACE                  VARCHAR2(1000)
);

-- Un documento con enlace no tiene archivo: no lleva tipo de archivo ni ruta.
ALTER TABLE DOCUMENTOS_ADJUNTOS MODIFY (TIPO_DOCUMENTO NULL, RUTA_ARCHIVO NULL);

ALTER TABLE DOCUMENTOS_ADJUNTOS ADD CONSTRAINT FK_DOCUMENTOS_TIPO_DOC_INST
    FOREIGN KEY (ID_TIPO_DOCUMENTO_INST) REFERENCES TIPOS_DOCUMENTO_INSTITUCIONAL (ID);

ALTER TABLE DOCUMENTOS_ADJUNTOS ADD CONSTRAINT CK_DOCUMENTOS_TAMANO
    CHECK (TAMANO_BYTES IS NULL OR TAMANO_BYTES > 0);

-- Archivo (o ruta declarada) O enlace institucional de SharePoint; el enlace nunca usa el prefijo
-- interno del almacen ni cuenta para el tamano del expediente.
ALTER TABLE DOCUMENTOS_ADJUNTOS ADD CONSTRAINT CK_DOCUMENTOS_ORIGEN CHECK (
    (ENLACE IS NULL AND RUTA_ARCHIVO IS NOT NULL AND TIPO_DOCUMENTO IS NOT NULL)
    OR (ENLACE IS NOT NULL AND RUTA_ARCHIVO IS NULL AND TIPO_DOCUMENTO IS NULL AND TAMANO_BYTES IS NULL
        AND (ENLACE LIKE 'https://upeuedupe.sharepoint.com/%' OR ENLACE LIKE 'https://upeuedupe-my.sharepoint.com/%'))
);

CREATE INDEX IX_DOCUMENTOS_TIPO_DOC_INST ON DOCUMENTOS_ADJUNTOS (ID_TIPO_DOCUMENTO_INST);

-- ---------------------------- Codigo de tramite ------------------------------
-- Empieza despues del mayor TR-AAAA-NNNNN que ya exista, para no chocar con UK_EXPEDIENTES_CODIGO.
DECLARE
    v_inicio NUMBER;
BEGIN
    SELECT NVL(MAX(TO_NUMBER(SUBSTR(CODIGO_TRAMITE, 9))), 0) + 1 INTO v_inicio
      FROM EXPEDIENTES
     WHERE REGEXP_LIKE(CODIGO_TRAMITE, '^TR-[0-9]{4}-[0-9]{5,}$');
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_CODIGO_TRAMITE START WITH ' || v_inicio
                      || ' INCREMENT BY 1 NOCACHE NOCYCLE';
END;
/

-- ------------------------------ Datos iniciales ------------------------------

INSERT INTO CATEGORIAS_TRAMITE (CODIGO, NOMBRE, DESCRIPCION)
SELECT v.CODIGO, v.NOMBRE, v.DESCRIPCION FROM (
    SELECT 'ACADEMICO' CODIGO, UNISTR('Tr\00e1mites acad\00e9micos') NOMBRE,
           UNISTR('Asistencia, cursos, evaluaciones y matr\00edcula') DESCRIPCION FROM DUAL UNION ALL
    SELECT 'ECONOMICO', UNISTR('Tr\00e1mites econ\00f3micos'),
           'Pagos, devoluciones, deudas y beneficios' FROM DUAL UNION ALL
    SELECT 'CONSTANCIAS', 'Constancias y certificados',
           UNISTR('Documentos oficiales sobre la situaci\00f3n acad\00e9mica') FROM DUAL
) v
WHERE NOT EXISTS (SELECT 1 FROM CATEGORIAS_TRAMITE c WHERE c.CODIGO = v.CODIGO);

INSERT INTO DESTINATARIOS (CODIGO, NOMBRE)
SELECT v.CODIGO, v.NOMBRE FROM (
    SELECT 'COORD_ACADEMICA' CODIGO, UNISTR('Coordinaci\00f3n Acad\00e9mica') NOMBRE FROM DUAL UNION ALL
    SELECT 'DIR_ESCUELA', UNISTR('Direcci\00f3n de Escuela') FROM DUAL UNION ALL
    SELECT 'SEC_ACADEMICA', UNISTR('Secretar\00eda Acad\00e9mica') FROM DUAL UNION ALL
    SELECT 'TESORERIA', UNISTR('Tesorer\00eda') FROM DUAL UNION ALL
    SELECT 'BIENESTAR', 'Bienestar Universitario' FROM DUAL
) v
WHERE NOT EXISTS (SELECT 1 FROM DESTINATARIOS d WHERE d.CODIGO = v.CODIGO);

INSERT INTO TIPOS_DOCUMENTO_INSTITUCIONAL (CODIGO, NOMBRE, DESCRIPCION)
SELECT v.CODIGO, v.NOMBRE, v.DESCRIPCION FROM (
    SELECT 'FUT' CODIGO, UNISTR('Formulario \00danico de Tr\00e1mite (FUT)') NOMBRE,
           'Solicitud firmada con el detalle del pedido' DESCRIPCION FROM DUAL UNION ALL
    SELECT 'DNI', 'Copia de DNI', 'Ambas caras, legible' FROM DUAL UNION ALL
    SELECT 'VOUCHER', 'Voucher de pago', 'Comprobante del pago del derecho de tramite' FROM DUAL UNION ALL
    SELECT 'CERT_MEDICO', UNISTR('Certificado m\00e9dico'), 'Emitido por un establecimiento de salud' FROM DUAL UNION ALL
    SELECT 'SILABO', UNISTR('S\00edlabo del curso'), 'Visado por la universidad de origen' FROM DUAL UNION ALL
    SELECT 'RECORD_NOTAS', UNISTR('R\00e9cord de notas'), 'Historial de calificaciones' FROM DUAL UNION ALL
    SELECT 'CARTA_MOTIVOS', 'Carta de motivos', UNISTR('Explicaci\00f3n de la situaci\00f3n del estudiante') FROM DUAL UNION ALL
    SELECT 'OTRO', 'Otro documento', 'Documento adicional de sustento' FROM DUAL
) v
WHERE NOT EXISTS (SELECT 1 FROM TIPOS_DOCUMENTO_INSTITUCIONAL t WHERE t.CODIGO = v.CODIGO);

INSERT INTO TIPOS_SOLICITUD (ID_CATEGORIA, CODIGO, NOMBRE, ID_DESTINATARIO_SUGERIDO)
SELECT c.ID, v.CODIGO, v.NOMBRE, d.ID FROM (
    SELECT 'ACADEMICO' CATEGORIA, 'JUSTIF_INASISTENCIA' CODIGO, UNISTR('Justificaci\00f3n de inasistencias') NOMBRE,
           'COORD_ACADEMICA' DESTINATARIO FROM DUAL UNION ALL
    SELECT 'ACADEMICO', 'CONVALIDACION', UNISTR('Convalidaci\00f3n de cursos'), 'DIR_ESCUELA' FROM DUAL UNION ALL
    SELECT 'ACADEMICO', 'RETIRO_CURSO', 'Retiro de curso', 'COORD_ACADEMICA' FROM DUAL UNION ALL
    SELECT 'ACADEMICO', 'EXAMEN_REZAGADO', 'Examen rezagado', 'COORD_ACADEMICA' FROM DUAL UNION ALL
    SELECT 'ACADEMICO', 'RESERVA_MATRICULA', UNISTR('Reserva de matr\00edcula'), 'SEC_ACADEMICA' FROM DUAL UNION ALL
    SELECT 'ECONOMICO', 'DEVOLUCION_PAGO', UNISTR('Devoluci\00f3n de pago'), 'TESORERIA' FROM DUAL UNION ALL
    SELECT 'ECONOMICO', 'FRACCIONAMIENTO', 'Fraccionamiento de deuda', 'TESORERIA' FROM DUAL UNION ALL
    SELECT 'ECONOMICO', 'BECA_DESCUENTO', 'Beca o descuento', 'BIENESTAR' FROM DUAL UNION ALL
    SELECT 'CONSTANCIAS', 'CONSTANCIA_ESTUDIOS', 'Constancia de estudios', 'SEC_ACADEMICA' FROM DUAL UNION ALL
    SELECT 'CONSTANCIAS', 'CERTIFICADO_ESTUDIOS', 'Certificado de estudios', 'SEC_ACADEMICA' FROM DUAL
) v
JOIN CATEGORIAS_TRAMITE c ON c.CODIGO = v.CATEGORIA
JOIN DESTINATARIOS d ON d.CODIGO = v.DESTINATARIO
WHERE NOT EXISTS (SELECT 1 FROM TIPOS_SOLICITUD t WHERE t.CODIGO = v.CODIGO);

-- OBLIGATORIO = 1: lo exige el registro. 0: recomendado (se muestra, no se exige).
INSERT INTO REQUISITOS_TIPO_SOLICITUD (ID_TIPO_SOLICITUD, ID_TIPO_DOCUMENTO, OBLIGATORIO)
SELECT t.ID, d.ID, v.OBLIGATORIO FROM (
    SELECT 'JUSTIF_INASISTENCIA' TIPO, 'FUT' DOCUMENTO, 1 OBLIGATORIO FROM DUAL UNION ALL
    SELECT 'JUSTIF_INASISTENCIA', 'CERT_MEDICO', 0 FROM DUAL UNION ALL
    SELECT 'CONVALIDACION', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'CONVALIDACION', 'SILABO', 1 FROM DUAL UNION ALL
    SELECT 'CONVALIDACION', 'RECORD_NOTAS', 1 FROM DUAL UNION ALL
    SELECT 'CONVALIDACION', 'VOUCHER', 1 FROM DUAL UNION ALL
    SELECT 'RETIRO_CURSO', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'EXAMEN_REZAGADO', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'EXAMEN_REZAGADO', 'VOUCHER', 1 FROM DUAL UNION ALL
    SELECT 'EXAMEN_REZAGADO', 'CERT_MEDICO', 0 FROM DUAL UNION ALL
    SELECT 'RESERVA_MATRICULA', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'RESERVA_MATRICULA', 'VOUCHER', 1 FROM DUAL UNION ALL
    SELECT 'DEVOLUCION_PAGO', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'DEVOLUCION_PAGO', 'DNI', 1 FROM DUAL UNION ALL
    SELECT 'DEVOLUCION_PAGO', 'VOUCHER', 1 FROM DUAL UNION ALL
    SELECT 'FRACCIONAMIENTO', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'BECA_DESCUENTO', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'BECA_DESCUENTO', 'RECORD_NOTAS', 1 FROM DUAL UNION ALL
    SELECT 'BECA_DESCUENTO', 'CARTA_MOTIVOS', 0 FROM DUAL UNION ALL
    SELECT 'CONSTANCIA_ESTUDIOS', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'CONSTANCIA_ESTUDIOS', 'VOUCHER', 1 FROM DUAL UNION ALL
    SELECT 'CERTIFICADO_ESTUDIOS', 'FUT', 1 FROM DUAL UNION ALL
    SELECT 'CERTIFICADO_ESTUDIOS', 'VOUCHER', 1 FROM DUAL
) v
JOIN TIPOS_SOLICITUD t ON t.CODIGO = v.TIPO
JOIN TIPOS_DOCUMENTO_INSTITUCIONAL d ON d.CODIGO = v.DOCUMENTO
WHERE NOT EXISTS (SELECT 1 FROM REQUISITOS_TIPO_SOLICITUD r
                  WHERE r.ID_TIPO_SOLICITUD = t.ID AND r.ID_TIPO_DOCUMENTO = d.ID);

COMMIT;

