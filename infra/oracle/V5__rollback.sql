-- ADVERTENCIA: solo con autorizacion y despues de un respaldo Data Pump verificado.
--   * Se pierden la categoria, el tipo de solicitud y el destinatario de los expedientes, el tipo
--     institucional y el tamano de los documentos, y los catalogos completos.
--   * Los documentos con ENLACE de SharePoint se BORRAN: sin la columna ENLACE no tienen archivo
--     ni ruta, y RUTA_ARCHIVO y TIPO_DOCUMENTO vuelven a ser NOT NULL. TOTAL_DOCUMENTOS se recalcula.
--   * Los codigos TR-AAAA-NNNNN ya asignados se conservan.
-- No toca los archivos del almacen ni ningun otro dato de los expedientes. Las tablas se borran con PURGE
-- (sin papelera) para que el esquema quede igual que antes de V5.
