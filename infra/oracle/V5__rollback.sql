WHENEVER SQLERROR CONTINUE
SET ECHO ON

DROP INDEX UX_EXPEDIENTES_TIPO_EN_CURSO;
DROP SEQUENCE SEQ_CODIGO_TRAMITE;

DELETE FROM DOCUMENTOS_ADJUNTOS WHERE ENLACE IS NOT NULL;
UPDATE EXPEDIENTES e
   SET TOTAL_DOCUMENTOS = (SELECT COUNT(*) FROM DOCUMENTOS_ADJUNTOS d WHERE d.ID_EXPEDIENTE = e.ID);
COMMIT;

ALTER TABLE DOCUMENTOS_ADJUNTOS DROP CONSTRAINT CK_DOCUMENTOS_ORIGEN;
ALTER TABLE DOCUMENTOS_ADJUNTOS DROP CONSTRAINT CK_DOCUMENTOS_TAMANO;
ALTER TABLE DOCUMENTOS_ADJUNTOS DROP CONSTRAINT FK_DOCUMENTOS_TIPO_DOC_INST;
DROP INDEX IX_DOCUMENTOS_TIPO_DOC_INST;
ALTER TABLE DOCUMENTOS_ADJUNTOS DROP (ID_TIPO_DOCUMENTO_INST, TAMANO_BYTES, ENLACE);
ALTER TABLE DOCUMENTOS_ADJUNTOS MODIFY (TIPO_DOCUMENTO NOT NULL, RUTA_ARCHIVO NOT NULL);

ALTER TABLE EXPEDIENTES DROP CONSTRAINT FK_EXPEDIENTES_CATEGORIA;
ALTER TABLE EXPEDIENTES DROP CONSTRAINT FK_EXPEDIENTES_TIPO_SOLICITUD;
ALTER TABLE EXPEDIENTES DROP CONSTRAINT FK_EXPEDIENTES_DESTINATARIO;
DROP INDEX IX_EXPEDIENTES_TIPO_SOLICITUD;
DROP INDEX IX_EXPEDIENTES_CATEGORIA;
DROP INDEX IX_EXPEDIENTES_DESTINATARIO;
ALTER TABLE EXPEDIENTES DROP (ID_CATEGORIA, ID_TIPO_SOLICITUD, ID_DESTINATARIO);

DROP TABLE REQUISITOS_TIPO_SOLICITUD PURGE;
DROP TABLE TIPOS_SOLICITUD PURGE;
DROP TABLE TIPOS_DOCUMENTO_INSTITUCIONAL PURGE;
DROP TABLE DESTINATARIOS PURGE;
