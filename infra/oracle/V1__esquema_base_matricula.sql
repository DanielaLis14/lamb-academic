-- =============================================================================
-- LAMB Academic - V1: tablas base de Matricula (solo para una base NUEVA)
-- Ejecutar conectado como LAMB_APP sobre un esquema vacio, antes de V2.
--
-- Reproduce las tablas PERIODOS, MATRICULAS y DETALLE_MATRICULA tal como existian antes
-- de V2; V2 y V4 les agregan sus columnas y restricciones. En una base que ya tiene estas
-- tablas (la base DEV de LAMB) NO se ejecuta: falla en el primer CREATE TABLE sin cambiar nada.
--
-- Orden completo en una base nueva: V1, V2, V4 y, opcional, V3 (datos ficticios).
-- =============================================================================

WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET ECHO ON

CREATE TABLE PERIODOS (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO        VARCHAR2(20)  NOT NULL,
    NOMBRE        VARCHAR2(100) NOT NULL,
    FECHA_INICIO  DATE NOT NULL,
    FECHA_FIN     DATE NOT NULL,
    ESTADO        VARCHAR2(20)  NOT NULL,
    CONSTRAINT PK_PERIODOS PRIMARY KEY (ID),
    CONSTRAINT UK_PERIODOS_CODIGO UNIQUE (CODIGO)
);

CREATE TABLE MATRICULAS (
    ID             NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ESTUDIANTE_ID  NUMBER NOT NULL,
    PERIODO_ID     NUMBER NOT NULL,
    FECHA          DATE NOT NULL,
    ESTADO         VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_MATRICULAS PRIMARY KEY (ID)
);

CREATE TABLE DETALLE_MATRICULA (
    ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MATRICULA_ID  NUMBER NOT NULL,
    SECCION_ID    NUMBER NOT NULL,
    CONSTRAINT PK_DETALLE_MATRICULA PRIMARY KEY (ID),
    CONSTRAINT FK_DETALLE_MATRICULA FOREIGN KEY (MATRICULA_ID) REFERENCES MATRICULAS (ID)
);

EXIT SUCCESS
